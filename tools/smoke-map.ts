// Quick check of the map endpoints against live data (no key needed).
import { GtfsDb } from '../apps/server/src/gtfs/db.ts';
import { currentDbPath } from '../apps/server/src/gtfs/import.ts';
import { buildApp } from '../apps/server/src/api/app.ts';
import { Boards } from '../apps/server/src/api/boards.ts';
import { systemClock } from '../apps/server/src/live/clock.ts';
import { Ingest } from '../apps/server/src/live/ingest.ts';
import { LiveManager } from '../apps/server/src/live/manager.ts';
import { LiveStore } from '../apps/server/src/live/store.ts';
import { BikesFeed } from '../apps/server/src/live/bikes.ts';
const db = new GtfsDb((await currentDbPath('data'))!);
const store = new LiveStore();
const ingest = new Ingest({ store, clock: systemClock, routeType: (id) => (db.routes().get(id)?.mode === 'bus' ? 3 : 0) });
const m = new LiveManager({ apiKey: null, userAgent: 't-walk-dev', clock: systemClock, ingest, routesByType: db.routeIdsByType(), log: () => {} });
const bikes = new BikesFeed({ userAgent: 't-walk-dev' });
m.start(); bikes.start();
await new Promise((r) => setTimeout(r, 6000));
const boards = new Boards({ getDb: () => db, store, ingest, clock: systemClock });
const app = await buildApp({ getDb: () => db, boards, store, bikes, clock: systemClock });
let t = performance.now();
const lines = await app.inject({ url: '/api/map/lines', headers: { 'accept-encoding': 'gzip' } });
console.log('lines', lines.statusCode, (performance.now() - t).toFixed(0) + 'ms', lines.rawPayload.length, 'bytes gz', 'etag', lines.headers.etag);
const l = JSON.parse((await app.inject({ url: '/api/map/lines' })).body);
console.log(' features', l.features.length, 'points', l.features.reduce((a: number, f: any) => a + f.geometry.coordinates.length, 0), 'routes', new Set(l.features.map((f: any) => f.properties.routeId)).size);
console.log(' 304 on revalidate:', (await app.inject({ url: '/api/map/lines', headers: { 'if-none-match': lines.headers.etag as string } })).statusCode);
const st = JSON.parse((await app.inject({ url: '/api/map/stations' })).body);
console.log('stations', st.length, st.find((s: any) => s.id === 'place-pktrm'));
const b1 = JSON.parse((await app.inject({ url: '/api/map/lines/1' })).body);
console.log('bus 1 shapes', b1.features.length);
const stops = JSON.parse((await app.inject({ url: '/api/map/stops?bbox=-71.07,42.35,-71.05,42.36' })).body);
console.log('bus stops in box', stops.stops.length);
const veh = [...store.vehicles.items.values()].find((v) => v.routeId === 'Red');
const d = await app.inject({ url: `/api/vehicles/${veh!.id}` });
const dj = JSON.parse(d.body);
console.log('vehicle', d.statusCode, dj.vehicle.label, dj.vehicle.headsign, 'shape', dj.vehicle.shapeId, 'next stops', dj.stops.slice(0, 4).map((s: any) => s.name).join(' → '));
const bk = JSON.parse((await app.inject({ url: '/api/bikes' })).body);
console.log('bikes', bk.stations.length, 'age', Math.round((Date.now() - bk.updatedAt) / 1000) + 's', bk.stations[0]);
await app.listen({ port: 0 });
const port = (app.server.address() as any).port;
const res = await fetch(`http://127.0.0.1:${port}/api/map/vehicles?bbox=-71.12,42.33,-71.02,42.38`);
const reader = res.body!.getReader(); let txt = ''; const dec = new TextDecoder(); const until = Date.now() + 14000;
while (Date.now() < until) { const { value, done } = await reader.read(); if (done) break; txt += dec.decode(value); if ((txt.match(/event: diff/g) ?? []).length >= 2) break; }
const evs = txt.split('\n\n').filter(Boolean).map((b) => ({ type: b.split('\n')[0]!.slice(7), data: JSON.parse(b.split('\n')[1]!.slice(6)) }));
for (const e of evs) console.log('stream', e.type, e.type === 'snapshot' ? e.data.vehicles.length + ' vehicles' : e.type === 'diff' ? `${e.data.upserts.length} up, ${e.data.removes.length} gone` : '');
reader.cancel(); m.stop(); bikes.stop(); await app.close(); process.exit(0);
